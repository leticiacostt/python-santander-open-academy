#percorrendo lista
mercado = ["café", "carne", "iogurte", "refrigerante", "pão"]
for item in mercado:
    print(item)

#percorrendo strings
nome = "Leticia"
for letra in nome:
    print(letra)

#usando números
for numero in range(10):
    print(numero)

#começando em outro numero
for numero in range (3, 8):
    print(numero)

#pulando numeros
for numero in range(0, 11, 2):
    print(numero) 

#contagem regressiva
for numero in range(10, 0, -1):
    print(numero)